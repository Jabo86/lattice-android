/// Arabo: l'interfaccia si specchia. forceRTL viene ricordato dal sistema e vale dal
/// prossimo avvio; per l'avvio in corso la direzione la impone lo stile del contenitore
/// radice (vedi Shell in App.js), così la scelta ha effetto subito senza chiedere un riavvio.
function applyRTL(on) {
  try {
    I18nManager.allowRTL(true);
    if (I18nManager.isRTL !== !!on) I18nManager.forceRTL(!!on);
  } catch (e) { /* piattaforma senza supporto: resta LTR */ }
}

const I18nCtx = createContext({ lang: "it", t: (k) => k, setLang: () => {}, chosen: true, rtl: false });
export const useI18n = () => useContext(I18nCtx);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState("it");
  // null = sto ancora leggendo il disco · false = non l'ha mai scelta · true = scelta fatta
  const [chosen, setChosen] = useState(null);
  useEffect(() => {
    SecureStore.getItemAsync(KEY).then((v) => {
      if (v && UI_LANG_CODES.indexOf(v) >= 0) { setLangState(v); applyRTL(isRTLLang(v)); setChosen(true); }
      else setChosen(false);
    }).catch(() => setChosen(false));
  }, []);
  const setLang = useCallback((l) => {
    if (UI_LANG_CODES.indexOf(l) < 0) return;
    setLangState(l);
    applyRTL(isRTLLang(l));
    setChosen(true);
    SecureStore.setItemAsync(KEY, l).catch(() => {});
  }, []);
  const t = useCallback((key, vars) => {
    let s = (TR[lang] && TR[lang][key]) || (lang === "it" ? undefined : TR.en[key]) || TR.it[key] || key;
    if (vars) for (const k in vars) s = s.replace(new RegExp("\\{" + k + "\\}", "g"), String(vars[k]));
    return s;
  }, [lang]);
  return <I18nCtx.Provider value={{ lang, t, setLang, chosen, rtl: isRTLLang(lang) }}>{children}</I18nCtx.Provider>;
}
